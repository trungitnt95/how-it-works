<h3>Cách bỏ thuốc hiệu quả</h3>
<ol>
<li><strong>Chuẩn bị:</strong> chọn ngày bỏ trong 1–2 tuần, báo gia đình, bạn bè, đồng nghiệp; dọn bỏ thuốc lá, bật lửa, gạt tàn; xác định tình huống dễ thèm thuốc (cà phê, rượu bia, căng thẳng, sau bữa ăn) và kế hoạch thay thế.</li>
